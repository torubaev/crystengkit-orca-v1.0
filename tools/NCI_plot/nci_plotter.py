def element_symbol_from_wfn_label(label: str) -> Optional[str]:
    match = re.match(r"^([A-Za-z]{1,3})\d*$", label.strip())
    if not match:
        return None
    letters = match.group(1)
    candidates = [letters[:1].upper() + letters[1:].lower()]
    if len(letters) >= 2:
        candidates.append(letters[:1].upper() + letters[1:2].lower())
    for candidate in candidates:
        if candidate in ELEMENT_SYMBOLS:
            return candidate
    return None


def configure_pyvista_defaults(pv_module, plotter, background="black", parallel_projection=True, antialiasing=None, extent=1.0):
    """Apply conservative PyVista defaults that work on limited OpenGL contexts."""
    try:
        pv_module.global_theme.multi_samples = 0
    except Exception:
        pass

    try:
        pv_module.global_theme.smooth_shading = False
    except Exception:
        pass

    try:
        bg = str(background or "black").strip().lower()
        plotter.set_background(background, top=HQ_BACKGROUND_TOP.get(bg))
    except Exception:
        try:
            plotter.set_background("black")
        except Exception:
            pass

    if antialiasing:
        try:
            plotter.enable_anti_aliasing(antialiasing)
        except Exception:
            pass

    try:
        plotter.enable_depth_peeling(number_of_peels=8, occlusion_ratio=0.0)
    except Exception:
        pass

    try:
        plotter.renderer.SetTwoSidedLighting(True)
    except Exception:
        pass

    if parallel_projection:
        try:
            plotter.enable_parallel_projection()
        except Exception:
            pass

    try:
        plotter.remove_all_lights()
    except Exception:
        pass

    try:
        extent = max(float(extent), 1.0)
    except Exception:
        extent = 1.0

    light_specs = [
        ("headlight", None, 0.72),
        ("camera light", None, 0.34),
        ("scene light", (2.6 * extent, -3.4 * extent, 4.2 * extent), 0.56),
        ("scene light", (-3.0 * extent, 2.4 * extent, 3.6 * extent), 0.30),
        ("scene light", (0.0, 3.2 * extent, -2.6 * extent), 0.18),
    ]

    for light_type, position, intensity in light_specs:
        try:
            if light_type in {"headlight", "camera light"}:
                light = pv_module.Light(light_type=light_type)
            else:
                light = pv_module.Light(
                    position=position,
                    focal_point=(0.0, 0.0, 0.0),
                    color="white",
                    light_type="scene light",
                )
            light.intensity = intensity
            plotter.add_light(light)
        except Exception:
            pass


