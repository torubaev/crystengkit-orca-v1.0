    def schedule_live_plot_update(self, *_args) -> None:
        """Debounce control changes and refresh an already-open NCI scene."""
        if not self.is_plotter_alive() or self.rdg_cube is None or self.signrho_cube is None:
            return
        if self.live_update_after_id is not None:
            try:
                self.root.after_cancel(self.live_update_after_id)
            except tk.TclError:
                pass
        self.live_update_after_id = self.root.after(220, self._run_live_plot_update)

    def schedule_surface_opacity_update(self, *_args) -> None:
        """Debounce an actor-only opacity change; never rebuild the scene."""
        if self.opacity_update_after_id is not None:
            try:
                self.root.after_cancel(self.opacity_update_after_id)
            except tk.TclError:
                pass
        self.opacity_update_after_id = self.root.after(40, self._apply_surface_opacity)

    def apply_live_background(self, *_args) -> None:
        """Change renderer colors without rebuilding actors, lights, or camera."""
        if not self.is_plotter_alive():
            return
        try:
            bg_color = self.background.get()
            text_color = contrast_text_color(bg_color)
            try:
                self.plotter.set_background(
                    bg_color,
                    top=HQ_BACKGROUND_TOP.get(str(bg_color).strip().lower()),
                )
            except Exception:
                self.plotter.set_background(bg_color)
            if self.show_scalar_bar.get():
                set_scalar_bar_text_color(self.plotter, text_color, NCI_SCALAR_BAR_TITLE)
            self.plotter.render()
        except (AttributeError, RuntimeError, tk.TclError):
            return

    def _apply_surface_opacity(self) -> None:
        self.opacity_update_after_id = None
        if not self.is_plotter_alive() or self.nci_surface_actor is None:
            return
        try:
            opacity = max(0.05, min(1.0, float(self.opacity.get())))
            prop = self.nci_surface_actor.GetProperty()
            prop.SetOpacity(opacity)
            self.plotter.render()
        except (TypeError, ValueError, AttributeError, tk.TclError):
            # Partial text-entry values must leave the existing scene intact.
            return

    def _run_live_plot_update(self) -> None:
        self.live_update_after_id = None
        if not self.plot_update_in_progress:
            self.update_plot(live=True)

    def recent_wavefunction_files(self) -> list[str]:
        values = self.config.get("recent_wavefunction_files", [])
        if isinstance(values, list):
            return [str(item) for item in values if str(item).strip()][:MAX_RECENT_FILES]
        return []

    def remember_wavefunction_file(self, path: Path) -> None:
        clean = str(path)
        recent = [clean] + [
            item for item in self.recent_wavefunction_files()
            if os.path.normcase(item) != os.path.normcase(clean)
        ]
        self.config["recent_wavefunction_files"] = recent[:MAX_RECENT_FILES]
        try:
            self.wavefunction_combo.configure(values=self.config["recent_wavefunction_files"])
        except Exception:
            pass
        self.save_config()

    def start_multiwfn_locator(self) -> None:
        if self.multiwfn_path.get().strip():
            return

        def worker() -> None:
            found = find_multiwfn_deep()
            self.root.after(0, lambda: self.finish_multiwfn_locator(found))

        threading.Thread(target=worker, daemon=True).start()

    def finish_multiwfn_locator(self, found: Optional[str]) -> None:
        if found and not self.multiwfn_path.get().strip():
            self.multiwfn_path.set(found)
            self.save_config()
            if self.auto_start_requested:
                self.root.after(250, self.auto_start_from_initial_wavefunction)

    def auto_start_from_initial_wavefunction(self) -> None:
        if not self.auto_start_requested:
            return
        if not self.wavefunction_path.get().strip():
            return
        if not self.multiwfn_path.get().strip() and not find_multiwfn():
            self.log("Automatic NCI plotting is waiting for Multiwfn detection.")
            return
        self.auto_start_requested = False
        self.log("Automatic NCI workflow started from the selected wavefunction file.")
        self.start_generate_nci(auto_open=True)

